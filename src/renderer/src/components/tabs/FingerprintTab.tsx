import { useToast } from '../../hooks/useToasts'

interface Props {
  profile: ProfileData
  setProfile: (patch: Partial<ProfileData>) => void
}

/** Validated number field with min/max constraints. */
function FpNum({
  label,
  value,
  onChange,
  min,
  max,
  step,
  fullWidth = true
}: {
  label: string
  value: number
  onChange: (v: number) => void
  min?: number
  max?: number
  step?: number
  fullWidth?: boolean
}): React.JSX.Element {
  const [error, setError] = useState(false)
  return (
    <TextField
      label={label}
      type="number"
      size="small"
      fullWidth={fullWidth}
      value={String(value)}
      error={error}
      onChange={(e) => {
        const n = Number(e.target.value)
        const outOfRange = (min !== undefined && n < min) || (max !== undefined && n > max)
        setError(outOfRange)
        if (!outOfRange) onChange(n)
      }}
      helperText={error ? `Range: ${min ?? '−∞'} – ${max ?? '∞'}` : undefined}
      slotProps={step ? { htmlInput: { step } } : undefined}
    />
  )
}

/** Binds one fingerprint text field to the draft. */
function Fp<T extends keyof FingerprintConfig>({
  label,
  fp,
  field,
  onChange,
  type = 'text',
  fullWidth = true
}: {
  label: string
  fp: FingerprintConfig
  field: T
  onChange: (patch: Partial<FingerprintConfig>) => void
  type?: string
  fullWidth?: boolean
}): React.JSX.Element {
  return (
    <TextField
      label={label}
      type={type}
      size="small"
      fullWidth={fullWidth}
      value={String(fp[field])}
      onChange={(e) => {
        const raw = e.target.value
        const value = type === 'number' ? Number(raw) : raw
        onChange({ [field]: value } as Partial<FingerprintConfig>)
      }}
    />
  )
}

/** The Fingerprint editor tab. */
export function FingerprintTab({ profile, setProfile }: Props): React.JSX.Element {
  const toast = useToast()
  const fp = profile.fingerprint
  const setFp = (patch: Partial<FingerprintConfig>): void => setProfile({ fingerprint: { ...fp, ...patch } })
  const [autoOpen, setAutoOpen] = useState(false)
  const [busyReal, setBusyReal] = useState(false)
  const [suggestOpen, setSuggestOpen] = useState(false)
  const [uaList, setUaList] = useState<
    Array<{ ua: string; browser: string; os: string; device: string; platform: string; version: string }>
  >([])
  const [uaFilter, setUaFilter] = useState('all')

  useEffect(() => {
    if (!suggestOpen || uaList.length) return
    void window.stealth.listUserAgents().then(setUaList).catch((e) => toast.error(String(e)))
  }, [suggestOpen, uaList.length, toast])

  const filteredUas = useMemo(() => {
    if (uaFilter === 'all') return uaList
    return uaList.filter((u) => u.browser === uaFilter)
  }, [uaList, uaFilter])

  const realValues = useMemo(() => {
    const nav = navigator as Navigator & { deviceMemory?: number }
    return {
      platform: nav.platform,
      language: nav.language,
      languages: [...(nav.languages ?? [])],
      cores: nav.hardwareConcurrency,
      memory: nav.deviceMemory ?? 4,
      touch: nav.maxTouchPoints,
      width: window.screen.width,
      height: window.screen.height,
      availWidth: window.screen.availWidth,
      availHeight: window.screen.availHeight,
      colorDepth: window.screen.colorDepth,
      dpr: window.devicePixelRatio
    }
  }, [])

  const fillWithReal = async (): Promise<void> => {
    setBusyReal(true)
    try {
      const sys = await window.stealth.getSystemInfo()
      setFp({
        platform: realValues.platform,
        language: realValues.language,
        languages: realValues.languages.length ? realValues.languages : [realValues.language],
        hardwareConcurrency: realValues.cores,
        deviceMemory: Math.max(1, Math.round((sys.totalMemoryGB / 2) / 2) * 2),
        maxTouchPoints: realValues.touch,
        screenWidth: realValues.width,
        screenHeight: realValues.height,
        screenAvailWidth: realValues.availWidth,
        screenAvailHeight: realValues.availHeight,
        screenColorDepth: realValues.colorDepth,
        screenPixelDepth: realValues.colorDepth,
        devicePixelRatio: realValues.dpr
      })
      toast.success('Filled with real system values.')
    } catch (e) {
      toast.error(String(e))
    } finally {
      setBusyReal(false)
    }
  }

  const deriveFromUA = async (): Promise<void> => {
    if (!fp.userAgent.trim()) {
      toast.error('Paste a user-agent string first.')
      return
    }
    try {
      const derived = await window.stealth.deriveFingerprintFromUA(fp.userAgent.trim(), fp.seed)
      setFp(derived)
      toast.success('Values re-derived from this user-agent.')
    } catch (e) {
      toast.error(String(e))
    }
  }

  return (
    <Box>
      {/* Action row */}
      <Stack direction="row" spacing={1} sx={{ mb: 2, flexWrap: 'wrap' }}>
        <Button size="small" variant="contained" startIcon={<AutoAwesomeIcon />} onClick={() => setAutoOpen(true)}>
          Auto-generate
        </Button>
        <Button size="small" variant="outlined" startIcon={<MonitorHeartIcon />} disabled={busyReal} onClick={() => void fillWithReal()}>
          Real values
        </Button>
        <Button size="small" variant="outlined" startIcon={<SyncIcon />} onClick={() => void deriveFromUA()}>
          Re-derive from UA
        </Button>
      </Stack>

      {/* User-Agent & Platform */}
      <SectionCard title="User-Agent & Platform" subtitle="navigator.userAgent, platform, languages">
        <Stack spacing={1.5}>
          <Stack direction="row" spacing={1} sx={{ alignItems: 'flex-start' }}>
            <TextField
              label="User-Agent"
              size="small"
              fullWidth
              multiline
              minRows={2}
              value={fp.userAgent}
              onChange={(e) => setFp({ userAgent: e.target.value })}
              placeholder="Mozilla/5.0 (Windows NT 10.0; Win64; x64) …"
            />
            <Button
              size="small"
              variant="outlined"
              startIcon={<LightbulbIcon />}
              onClick={() => setSuggestOpen(true)}
              sx={{ whiteSpace: 'nowrap', mt: 0.5 }}
            >
              Suggest
            </Button>
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <Fp label="Platform" fp={fp} field="platform" onChange={setFp} />
            <Fp label="oscpu (Firefox)" fp={fp} field="oscpu" onChange={setFp} />
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <Fp label="Language" fp={fp} field="language" onChange={setFp} />
            <TextField
              label="Languages (comma-sep)"
              size="small"
              fullWidth
              value={(fp.languages ?? []).join(', ')}
              onChange={(e) =>
                setFp({
                  languages: e.target.value
                    .split(',')
                    .map((s) => s.trim())
                    .filter(Boolean)
                })
              }
            />
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <Fp label="Timezone (IANA)" fp={fp} field="timezone" onChange={setFp} />
            <Fp label="TZ offset (min)" fp={fp} field="timezoneOffset" onChange={setFp} type="number" />
          </Stack>
        </Stack>
      </SectionCard>

      {/* Screen — with validation */}
      <SectionCard title="Screen" subtitle="Resolution, color depth, pixel ratio">
        <Stack spacing={1.5}>
          <Stack direction="row" spacing={1.5}>
            <FpNum label="Width" value={fp.screenWidth} onChange={(v) => setFp({ screenWidth: v })} min={320} max={7680} />
            <FpNum label="Height" value={fp.screenHeight} onChange={(v) => setFp({ screenHeight: v })} min={240} max={4320} />
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <FpNum label="Avail width" value={fp.screenAvailWidth} onChange={(v) => setFp({ screenAvailWidth: v })} min={320} max={7680} />
            <FpNum label="Avail height" value={fp.screenAvailHeight} onChange={(v) => setFp({ screenAvailHeight: v })} min={240} max={4320} />
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <FpNum label="Color depth" value={fp.screenColorDepth} onChange={(v) => setFp({ screenColorDepth: v })} min={1} max={48} />
            <FpNum label="Pixel depth" value={fp.screenPixelDepth} onChange={(v) => setFp({ screenPixelDepth: v })} min={1} max={48} />
            <FpNum label="devicePixelRatio" value={fp.devicePixelRatio} onChange={(v) => setFp({ devicePixelRatio: v })} min={0.25} max={4} step={0.25} />
          </Stack>
        </Stack>
      </SectionCard>

      {/* Hardware — with validation */}
      <SectionCard title="Hardware" subtitle="CPU cores, RAM, touch">
        <Stack spacing={1.5}>
          <Stack direction="row" spacing={1.5}>
            <FpNum label="CPU cores" value={fp.hardwareConcurrency} onChange={(v) => setFp({ hardwareConcurrency: v })} min={1} max={128} />
            <FpNum label="Memory (GB)" value={fp.deviceMemory} onChange={(v) => setFp({ deviceMemory: v })} min={1} max={256} />
            <FpNum label="Touch points" value={fp.maxTouchPoints} onChange={(v) => setFp({ maxTouchPoints: v })} min={0} max={10} />
          </Stack>
        </Stack>
      </SectionCard>

      {/* WebGL */}
      <SectionCard title="WebGL" subtitle="Vendor / renderer spoofing">
        <Stack spacing={1.5}>
          <Fp label="Vendor" fp={fp} field="webglVendor" onChange={setFp} />
          <Fp label="Renderer" fp={fp} field="webglRenderer" onChange={setFp} />
        </Stack>
      </SectionCard>

      {/* Canvas & Audio */}
      <SectionCard title="Canvas & Audio" subtitle="Seeded noise for hash randomization">
        <Stack spacing={1}>
          <Stack direction="row" spacing={2}>
            <FormControlLabel
              control={<Switch checked={fp.canvasNoiseEnabled} onChange={(e) => setFp({ canvasNoiseEnabled: e.target.checked })} size="small" />}
              label="Canvas noise"
            />
            <FormControlLabel
              control={<Switch checked={fp.audioNoiseEnabled} onChange={(e) => setFp({ audioNoiseEnabled: e.target.checked })} size="small" />}
              label="Audio noise"
            />
            <FormControlLabel
              control={<Switch checked={fp.webRTCLeakProtect} onChange={(e) => setFp({ webRTCLeakProtect: e.target.checked })} size="small" />}
              label="WebRTC protect"
            />
          </Stack>
          <Stack direction="row" spacing={1.5}>
            <Fp label="Canvas seed" fp={fp} field="canvasNoiseSeed" onChange={setFp} type="number" />
            <Fp label="Audio seed" fp={fp} field="audioNoiseSeed" onChange={setFp} type="number" />
          </Stack>
        </Stack>
      </SectionCard>

      {/* Fonts */}
      <SectionCard title="Fonts" subtitle="Enumerable fonts via document.fonts">
        <Stack spacing={1}>
          <FormControlLabel
            control={<Switch checked={fp.fontFingerprintProtection} onChange={(e) => setFp({ fontFingerprintProtection: e.target.checked })} size="small" />}
            label="Font fingerprint protection"
          />
          <TextField
            label="Custom fonts (one per line)"
            size="small"
            fullWidth
            multiline
            minRows={3}
            value={(fp.customFonts ?? []).join('\n')}
            onChange={(e) =>
              setFp({ customFonts: e.target.value.split('\n').map((s) => s.trim()).filter(Boolean) })
            }
          />
        </Stack>
      </SectionCard>

      {/* Geolocation */}
      <SectionCard title="Geolocation" subtitle="Block or spoof position">
        <Stack direction="row" spacing={1.5} sx={{ alignItems: 'center', flexWrap: 'wrap' }}>
          <FormControl size="small" sx={{ minWidth: 160 }}>
            <InputLabel>Mode</InputLabel>
            <Select
              label="Mode"
              value={fp.geolocation.mode}
              onChange={(e) => setFp({ geolocation: { ...fp.geolocation, mode: e.target.value as 'block' | 'spoof' } })}
            >
              <MenuItem value="block">Block</MenuItem>
              <MenuItem value="spoof">Spoof</MenuItem>
            </Select>
          </FormControl>
          {fp.geolocation.mode === 'spoof' && (
            <>
              <TextField
                label="Lat"
                type="number"
                size="small"
                value={String(fp.geolocation.latitude)}
                onChange={(e) => setFp({ geolocation: { ...fp.geolocation, latitude: Number(e.target.value) } })}
                sx={{ width: 120 }}
              />
              <TextField
                label="Lon"
                type="number"
                size="small"
                value={String(fp.geolocation.longitude)}
                onChange={(e) => setFp({ geolocation: { ...fp.geolocation, longitude: Number(e.target.value) } })}
                sx={{ width: 120 }}
              />
            </>
          )}
        </Stack>
      </SectionCard>

      {/* Privacy — doNotTrack, window.chrome, pluginsSpoof */}
      <SectionCard title="Privacy" subtitle="DoNotTrack, window.chrome, plugins spoofing">
        <Stack spacing={1}>
          <Stack direction="row" spacing={1.5}>
            <FormControl size="small" sx={{ minWidth: 180 }}>
              <InputLabel>Do Not Track</InputLabel>
              <Select
                label="Do Not Track"
                value={fp.doNotTrack ?? 'null'}
                onChange={(e) => {
                  const v = e.target.value
                  setFp({ doNotTrack: v === 'null' ? null : v })
                }}
              >
                <MenuItem value="null">Not specified</MenuItem>
                <MenuItem value="1">Enabled (1)</MenuItem>
                <MenuItem value="0">Disabled (0)</MenuItem>
              </Select>
            </FormControl>
            <FormControlLabel
              control={<Switch checked={fp.windowChromeSpoof} onChange={(e) => setFp({ windowChromeSpoof: e.target.checked })} size="small" />}
              label="Spoof window.chrome"
            />
            <FormControlLabel
              control={<Switch checked={fp.pluginsSpoof} onChange={(e) => setFp({ pluginsSpoof: e.target.checked })} size="small" />}
              label="Spoof plugins"
            />
          </Stack>
          <Alert severity="info" sx={{ borderRadius: 2, py: 0 }}>
            <Typography variant="caption">
              Seed: <code>{fp.seed}</code> — same seed reproduces the same fingerprint.
            </Typography>
          </Alert>
        </Stack>
      </SectionCard>

      <AutoGenerateDialog
        open={autoOpen}
        onClose={() => setAutoOpen(false)}
        onGenerated={(newFp) => {
          setFp(newFp)
          toast.success('Fingerprint generated — auto-saved.')
        }}
      />

      {/* UA Suggest dialog */}
      <Dialog open={suggestOpen} onClose={() => setSuggestOpen(false)} fullWidth maxWidth="md">
        <DialogTitle>Suggest realistic User-Agent</DialogTitle>
        <DialogContent>
          <Stack direction="row" spacing={1} sx={{ mb: 1.5, flexWrap: 'wrap' }}>
            {['all', 'chrome', 'edge', 'brave', 'firefox'].map((b) => (
              <Button
                key={b}
                size="small"
                variant={uaFilter === b ? 'contained' : 'outlined'}
                onClick={() => setUaFilter(b)}
              >
                {b}
              </Button>
            ))}
          </Stack>
          <Typography variant="caption" color="text.secondary" sx={{ mb: 1, display: 'block' }}>
            Pick a real browser UA from the built-in library. Selecting one also re-derives consistent platform /
            screen / GPU values from the same seed.
          </Typography>
          <List dense sx={{ maxHeight: 360, overflow: 'auto', border: '1px solid', borderColor: 'divider', borderRadius: 2 }}>
            {filteredUas.map((entry, i) => (
              <ListItemButton
                key={i}
                onClick={() => {
                  void (async () => {
                    try {
                      const derived = await window.stealth.deriveFingerprintFromUA(entry.ua, fp.seed)
                      setFp(derived)
                      setSuggestOpen(false)
                      toast.success(`Applied ${entry.browser} ${entry.version} (${entry.os}) UA`)
                    } catch (e) {
                      toast.error(String(e))
                    }
                  })()
                }}
              >
                <ListItemText
                  primary={
                    <Typography component="span" sx={{ fontWeight: 600, fontSize: 13 }}>
                      {`${entry.browser} ${entry.version} · ${entry.os} · ${entry.device}`}
                    </Typography>
                  }
                  secondary={
                    <Typography component="span" sx={{ fontSize: 11, wordBreak: 'break-all', display: 'block' }} color="text.secondary">
                      {entry.ua}
                    </Typography>
                  }
                />
              </ListItemButton>
            ))}
            {filteredUas.length === 0 && (
              <Typography variant="body2" color="text.secondary" sx={{ p: 2, textAlign: 'center' }}>
                Loading user-agent library…
              </Typography>
            )}
          </List>
        </DialogContent>
        <DialogActions>
          <Button onClick={() => setSuggestOpen(false)}>Close</Button>
        </DialogActions>
      </Dialog>
    </Box>
  )
}
